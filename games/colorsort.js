// ── Core rules ──────────────────────────────────────────────────────────
function isSolved(){
  return tubes.every(function(col){
    return col.length===0||(col.length===CAP&&col.every(function(c){return c===col[0];}));
  });
}
function isTubeDone(col){
  return col.length===CAP&&col.every(function(c){return c===col[0];});
}
function canPour(from,to){
  if(from===to)return false;
  var src=tubes[from],dst=tubes[to];
  if(!src.length)return false;
  if(dst.length>=CAP)return false;
  if(dst.length&&dst[dst.length-1]!==src[src.length-1])return false;
  return true;
}
function cloneTubes(){return tubes.map(function(c){return c.slice();});}

// How many units will pour from from → to right now
function pourCount(from,to){
  var src=tubes[from],dst=tubes[to];
  if(!src.length)return 0;
  var color=src[src.length-1];
  var n=0;
  while(src.length-1-n>=0&&src[src.length-1-n]===color&&dst.length+n<CAP)n++;
  return n;
}
function doPour(from,to){
  var snap=cloneTubes();
  var n=pourCount(from,to);
  if(!n)return false;
  var color=tubes[from][tubes[from].length-1];
  for(var i=0;i<n;i++){tubes[from].pop();tubes[to].push(color);}
  history.push(snap);
  moves++;
  _play('tap');
  return true;
}

