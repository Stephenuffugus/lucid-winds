// ── Interaction ─────────────────────────────────────────────────────────
function onTubeTap(ti){
  if(won)return;
  if(sel===-1){
    if(tubes[ti].length===0)return;
    sel=ti;renderTubes();return;
  }
  if(sel===ti){sel=-1;renderTubes();return;}
  if(!canPour(sel,ti)){
    // Invalid pour — switch selection to the new tube if it has something.
    sel=tubes[ti].length?ti:-1;renderTubes();return;
  }
  var from=sel,to=ti;
  var n=pourCount(from,to);
  doPour(from,to);
  sel=-1;
  renderTubes({to:to,count:n});
  updateStatus();
  if(isSolved())handleWin();
}

function undoMove(){
  if(!history.length||won)return;
  tubes=history.pop();
  moves=Math.max(0,moves-1);
  sel=-1;
  _play('tap');
  renderTubes();updateStatus();
}

function resetLevel(){
  if(won)return;
  loadLevel(levelIdx,true);
}

function handleWin(){
  won=true;solvedTs=Date.now();
  if(timerId){clearInterval(timerId);timerId=null;}
  _e('game_win');if(_playWin)_playWin();_sr('colorsort',{w:true,s:moves,lvl:levelIdx+1});
  var prog=loadProgress();
  if(levelIdx+1>prog)saveProgress(levelIdx+1);
  setTimeout(victoryOverlay,450);
}

